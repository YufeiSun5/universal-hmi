"""Reproduce intrinsic SVG sizes used by Flutter's pure connection geometry.

Run after changing the committed process SVGs; --check is a read-only gate.
The SVG viewBox is the drawing viewport, not a guessed equipment boundary.
"""
import argparse
import json
import math
from pathlib import Path
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'app/lib/features/process/symbol_sizes.dart'
EXAMPLES = {'example_plate_hx': 'plate-hx', 'example_pump': 'pump',
            'example_tank': 'tank', 'example_valve': 'valve'}


def sizes():
    catalog = json.loads((ROOT / 'app/assets/process/catalog.json').read_text(encoding='utf-8'))
    paths = {item['id']: ROOT / 'app' / item['path'] for item in catalog['items']}
    paths.update({key: ROOT / f'app/assets/process/examples/{name}.svg'
                  for key, name in EXAMPLES.items()})
    result = {}
    for key, path in sorted(paths.items()):
        box = [float(n) for n in ET.fromstring(path.read_bytes()).get('viewBox').replace(',', ' ').split()]
        assert len(box) == 4 and all(math.isfinite(n) for n in box) and min(box[2:]) > 0, path
        result[key] = box[2:]
    return result


def rendered():
    lines = ['// Generated by ci/process_symbol_geometry.py; do not edit by hand.',
             "import 'dart:ui';", '', 'const processSymbolSizes = <String, Size>{']
    for key, (width, height) in sizes().items():
        numbers = [str(int(n)) if n.is_integer() else repr(n) for n in (width, height)]
        lines.append(f"  '{key}': Size({numbers[0]}, {numbers[1]}),")
    return '\n'.join(lines + ['};', ''])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    content = rendered()
    if args.check:
        assert OUTPUT.read_text(encoding='utf-8') == content, 'Regenerate process symbol sizes'
    else:
        OUTPUT.write_text(content, encoding='utf-8', newline='\n')


if __name__ == '__main__':
    main()
